CREATE TABLE IF NOT EXISTS `gst_ledger_entries` (
  `id` VARCHAR(191) NOT NULL,
  `tenantId` VARCHAR(191) NOT NULL,
  `legalEntityId` VARCHAR(191) NOT NULL,
  `branchId` VARCHAR(191) NULL,
  `direction` ENUM('OUTWARD', 'INWARD') NOT NULL,
  `documentType` ENUM('SALES_INVOICE', 'VENDOR_INVOICE', 'CUSTOMER_CREDIT_NOTE', 'VENDOR_ADJUSTMENT') NOT NULL,
  `documentId` VARCHAR(191) NOT NULL,
  `documentLineId` VARCHAR(64) NOT NULL DEFAULT '',
  `documentNumber` VARCHAR(64) NOT NULL,
  `documentDate` DATE NOT NULL,
  `returnPeriod` VARCHAR(7) NOT NULL,
  `partyGstin` VARCHAR(20) NULL,
  `companyGstin` VARCHAR(20) NULL,
  `placeOfSupply` VARCHAR(100) NULL,
  `hsnSacCode` VARCHAR(16) NULL,
  `taxType` ENUM(
    'OUTPUT_CGST','OUTPUT_SGST','OUTPUT_IGST','OUTPUT_CESS',
    'INPUT_CGST','INPUT_SGST','INPUT_IGST','INPUT_CESS',
    'RCM_CGST','RCM_SGST','RCM_IGST'
  ) NOT NULL,
  `taxableValue` DECIMAL(18, 4) NOT NULL DEFAULT 0,
  `taxRate` DECIMAL(9, 4) NOT NULL DEFAULT 0,
  `taxAmount` DECIMAL(18, 4) NOT NULL DEFAULT 0,
  `isReverseCharge` BOOLEAN NOT NULL DEFAULT false,
  `itcEligibility` VARCHAR(40) NULL,
  `filingStatus` ENUM('NOT_FILED', 'INCLUDED_IN_DRAFT', 'FILED', 'AMENDED') NOT NULL DEFAULT 'NOT_FILED',
  `accountingVoucherId` VARCHAR(191) NULL,
  `postingEventId` VARCHAR(191) NULL,
  `sourceSnapshot` JSON NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `gst_ledger_doc_line_tax_key`(`tenantId`, `documentId`, `documentLineId`, `taxType`),
  INDEX `gst_ledger_le_period_idx`(`tenantId`, `legalEntityId`, `returnPeriod`),
  INDEX `gst_ledger_le_date_idx`(`tenantId`, `legalEntityId`, `documentDate`),
  INDEX `gst_ledger_doc_idx`(`tenantId`, `documentType`, `documentId`),
  INDEX `gst_ledger_filing_idx`(`tenantId`, `filingStatus`),
  CONSTRAINT `gst_ledger_entries_tenantId_fkey` FOREIGN KEY (`tenantId`) REFERENCES `tenants`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `gst_ledger_entries_legalEntityId_fkey` FOREIGN KEY (`legalEntityId`) REFERENCES `legal_entities`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
